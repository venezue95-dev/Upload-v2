def premiumize(text: str) -> str:
    """Reemplaza solo emojis con ID exacto; los demás quedan como fallback Unicode."""
    if not text:
        return text
    # Longest first protects multi-codepoint emoji and variation selectors.
    for emoji in sorted(CUSTOM_EMOJI_IDS, key=len, reverse=True):
        emoji_id = CUSTOM_EMOJI_IDS[emoji]
        text = text.replace(emoji, f'<tg-emoji emoji-id="{emoji_id}">{emoji}</tg-emoji>')
    return text
